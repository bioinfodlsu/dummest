#!/bin/bash
# Run steps 1-5 in order (replaces test-all.sh).
# Usage: ./run-steps.sh [--clean] [--max] [--force] [full|lite|full-over|lite-over|all]   (default variant: all)
# Default runs the Badread frameshift pipeline: step2-frameshift.sh inserts
# simulated nanopore reads after step 1, and steps 3-5 benchmark the
# <base>-fs reads. --clean skips the frameshift step and benchmarks the
# pristine step-1 files instead. --max adds bathsearch --max runs
# (lite / lite-over only). --force forwards to step1/frameshift/rename/
# precompute (without it, existing DBs are reused -- full is never
# regenerated by accident).
set -euo pipefail
trap 'echo "run-steps: FAILED at line $LINENO: $BASH_COMMAND (exit $?)" >&2' ERR
cd "$(dirname "$0")"
source ./config.sh

CLEAN=""
MAX=""
FORCE=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        --clean) CLEAN="--clean"; shift ;;
        --max) MAX="--max"; shift ;;
        --force) FORCE="--force"; shift ;;
        *) break ;;
    esac
done
VARIANT="${1:-all}"
case "$VARIANT" in
    full|lite|full-over|lite-over|all) ;;
    *) echo "Usage: $0 [--clean] [--max] [--force] [full|lite|full-over|lite-over|all]" >&2; exit 1 ;;
esac
if [[ -n "$MAX" && "$VARIANT" != "lite" && "$VARIANT" != "lite-over" ]]; then
    echo "run-steps: --max is only supported on lite/lite-over, ignoring --max" >&2
    MAX=""
fi

TAG="fs"
if [[ -n "$CLEAN" ]]; then TAG="clean"; fi

# Expand VARIANT to step-script variants (each step script also accepts
# "all", but we expand here so precompute + LAST prepare/run, which take
# single bases, stay variant-aware).
case "$VARIANT" in
    all) VARIANTS="full lite full-over lite-over" ;;
    *) VARIANTS="$VARIANT" ;;
esac

# Steps 1-2.5: build DBs (skip-if-exists unless --force; full safe).
# shellcheck disable=SC2086
./step1-create.sh "$VARIANT" $FORCE
if [[ -z "$CLEAN" ]]; then
    # shellcheck disable=SC2086
    ./step2-frameshift.sh "$VARIANT" $FORCE
fi
./step2-prepare.sh "$VARIANT"
if [[ -z "$CLEAN" ]]; then
    # shellcheck disable=SC2086
    ./step-2.5-rename-fs.sh "$VARIANT" $FORCE
fi

# Precompute 6-frame + MMseqs DBs for full-scale fs targets only.
# Lite / lite-over build per-run in tmpdir.
if [[ -z "$CLEAN" ]]; then
    for v in $VARIANTS; do
        case "$v" in
            full|full-over)
                # shellcheck disable=SC2086
                ./step3-dummer-precompute.sh "$v" $FORCE ;;
        esac
    done
fi

# shellcheck disable=SC2086
echo "run-steps: step4-dummer $CLEAN $VARIANT (cache fill) ..." >&2
{ time ./step4-dummer.sh $CLEAN "$VARIANT"; } &> "step4-dummer-$VARIANT-$TAG-no-seeds.log"
echo "run-steps: step4-dummer $CLEAN $VARIANT ..." >&2
# shellcheck disable=SC2086
# cache warm
{ time ./step4-dummer.sh $CLEAN "$VARIANT"; } &> "step4-dummer-$VARIANT-$TAG.log"
{ time ./step4-dummer.sh $CLEAN "$VARIANT" --gapped-pvalue 0.005; } &> "step4-dummer-$VARIANT-$TAG-fast.log"
echo "run-steps: step3-bathsearch $CLEAN $VARIANT ..." >&2
# shellcheck disable=SC2086
{ time ./step3-bathsearch.sh $CLEAN "$VARIANT"; } &> "step3-bathsearch-$VARIANT-$TAG.log"
echo "run-steps: step3-bathsearch --no-fs $CLEAN $VARIANT ..." >&2
# shellcheck disable=SC2086
{ time ./step3-bathsearch.sh --no-fs $CLEAN "$VARIANT"; } &> "step3-bathsearch-no-fs-$VARIANT-$TAG.log"
if [[ -n "$MAX" ]]; then
# shellcheck disable=SC2086
{ time ./step3-bathsearch.sh --max $CLEAN "$VARIANT"; } &> "step3-bathsearch-max-$VARIANT-$TAG.log"
# shellcheck disable=SC2086
{ time ./step3-bathsearch.sh --no-fs --max $CLEAN "$VARIANT"; } &> "step3-bathsearch-no-fs-max-$VARIANT-$TAG.log"
fi
echo "run-steps: step5-last (prepare then run) for: $VARIANTS ..." >&2
for v in $VARIANTS; do
    # shellcheck disable=SC2086
    { time ./step5-last.sh prepare "$v"; } &> "step5-last-prepare-$v-$TAG.log"
    # shellcheck disable=SC2086
    { time ./step5-last.sh run $CLEAN "$v"; } &> "step5-last-$v-$TAG.log"
done
